const BASE = 'assets/douyin-emoji/';

/// 正文里的 `[xxx]` 候选：表情名最长也就十来个字，别把整段方括号文字都当表情。
const TOKEN = /\[[^\[\]]{1,16}\]/g;

/// 把一个 token 换成 `{ url, width, height }`；不是抖音表情就返回 null。
export function douyinEmoji(key) {
  const hit = FILES.get(key);
  if (!hit) return null;
  const [file, width, height] = hit;
  return { url: `${BASE}${file}`, width, height };
}

/// 补全一条弹幕里缺图的表情：已有 `emoticons` 里没有的 token 才补，避免盖掉平台下发的图。
/// 一个都没补上时返回 `null`（调用方按「没有表情」处理，别塞个空数组进去）。
export function expandDouyinEmoticons(text, emoticons) {
  const value = text == null ? '' : String(text);
  if (!value.includes('[')) return emoticons && emoticons.length ? emoticons : null;
  const known = new Set((emoticons || []).map((item) => item?.key));
  const extra = [];
  for (const token of value.match(TOKEN) || []) {
    if (known.has(token)) continue;
    const hit = douyinEmoji(token);
    if (!hit) continue;
    known.add(token);
    extra.push({ key: token, url: hit.url, width: hit.width, height: hit.height, big: false });
  }
  if (!extra.length) return emoticons && emoticons.length ? emoticons : null;
  return [...(emoticons || []), ...extra];
}
